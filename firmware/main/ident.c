static const char GLYPH_KEYS[] = "0123456789ABCDEFGINOSTWXHMPLURZJKQVY./-: ";

static const uint8_t *glyph(char c)
{
    c = (char)toupper((unsigned char)c);
    for (size_t i = 0; GLYPH_KEYS[i]; i++) {
        if (GLYPH_KEYS[i] == c) {
            return GLYPHS[i];
        }
    }
    return GLYPHS[sizeof(GLYPH_KEYS) - 2]; /* space */
}

void ident_draw_text(uint8_t *rgb, int w, int h, int x, int y, int scale, uint32_t colour, const char *text)
{
    uint8_t r = colour >> 16, g = colour >> 8, b = colour;
    for (const char *p = text; *p; p++, x += 6 * scale) {
        const uint8_t *gl = glyph(*p);
        for (int row = 0; row < 7; row++) {
            for (int col = 0; col < 5; col++) {
                if (!(gl[row] & (0x10 >> col))) {
                    continue;
                }
                for (int sy = 0; sy < scale; sy++) {
                    int py = y + row * scale + sy;
                    if (py < 0 || py >= h) continue;
                    for (int sx = 0; sx < scale; sx++) {
                        int px = x + col * scale + sx;
                        if (px < 0 || px >= w) continue;
                        uint8_t *d = rgb + ((size_t)py * w + px) * 3;
                        d[0] = b; d[1] = g; d[2] = r;   /* frame buffer byte order is B,G,R */
                    }
                }
            }
        }
    }
}
